import assert from 'node:assert/strict';
import * as T from 'three';
import {PizzaSlice} from '../src/pizza/PizzaSlice';
import {CheeseSystem} from '../src/cheese/CheeseSystem';

const material=new T.MeshPhysicalMaterial();
const materials={cheese:material,underside:material,crumb:material,crust:material,dough:material,sauce:material,basil:material,strand:material};
const slices=Array.from({length:6},(_,i)=>new PizzaSlice(i,materials)),scene=new T.Scene();
slices.forEach(slice=>scene.add(slice.group));
const system=new CheeseSystem(slices,scene,material),moving=slices[1];
const step=()=>system.update(1/120);
system.beginPull(moving);moving.detached=moving.held=true;moving.group.position.y=.1;step();
const initial=system.metrics.active;
assert(initial>0);
moving.group.position.y=4.5;step();
assert.equal(system.metrics.active,0);
const old=system.strands.slice();assert(old.every(strand=>strand.extrusion?.active));
moving.group.position.y=.1;moving.held=false;system.beginPull(moving);moving.held=true;step();
assert.equal(system.metrics.active,initial,'early re-grab lost its bridges to retained broken roots');
assert(old.every(strand=>strand.extrusion?.active===false),'dead roots still occupy the new pull');
for(let i=0;i<250;i++)step();
assert.equal(system.metrics.active,initial,'continuous holding lost replacement bridges');
const replacements=system.strands.slice();
system.beginPull(moving);step();system.spawn(moving);
assert.deepEqual(system.strands,replacements,'repeated grab duplicated intact bridges');
const neighbor=slices[0],shared=system.strands.filter(strand=>strand.neighbor===neighbor);
neighbor.detached=true;system.beginPull(neighbor);neighbor.group.position.y=.1;step();
assert(shared.every(strand=>system.strands.includes(strand)&&!strand.broken));
assert.equal(system.strands.filter(strand=>(strand.moving===neighbor&&strand.neighbor===moving)||(strand.moving===moving&&strand.neighbor===neighbor)).length,shared.length);
assert(system.strands.some(strand=>strand.moving===neighbor),'free side failed to spawn');
moving.group.position.y=4.5;step();moving.group.position.y=.1;
const other=slices[2],deadShared=system.strands.filter(strand=>strand.broken&&strand.neighbor===other);
assert(deadShared.length>0);
const intact=system.strands.filter(strand=>!strand.broken);
system.beginPull(other);other.detached=true;other.group.position.y=.1;step();
assert(deadShared.every(strand=>strand.extrusion?.active===false));
assert(system.strands.some(strand=>strand.moving===other&&!strand.broken));
assert(intact.every(strand=>system.strands.includes(strand)&&!strand.broken));
system.clear();
moving.reset();moving.mozzarellaIntervals=()=>[];
system.beginPull(moving);moving.detached=true;moving.group.position.y=.1;
const pulls=system.pulls;for(let i=0;i<30;i++)step();
assert.equal(system.pulls,pulls+1);assert.equal(system.metrics.active,0);
console.log({initial,immediateRegrab:initial,intactShared:shared.length,noCoverageRetries:system.pulls-pulls});
system.clear();
